const normalizeUrl = (url) => {
  if (!url) return '#';
  if (url.startsWith('http://') || url.startsWith('https://') || url.startsWith('mailto:') || url.startsWith('tel:')) {
    return url;
  }
  return `https://${url}`;
};

export default function SocialElement({ data, isPreview = false }) {
  const links = data?.links || [];
  const activeLinks = links.filter((l) => l.active && l.url);

  const iconStyle = data?.iconStyle || 'filled';
  const colorMode = data?.colorMode || 'colored';
  const iconShape = data?.iconShape || 'circle';
  const iconSize = data?.iconSize || 'medium';

  if (activeLinks.length === 0) {
    return (
      <div className="w-full text-center py-4 border-t border-slate-200 mt-6 text-xs text-slate-400 italic">
        No active social links added. Click edit to add your social profiles.
      </div>
    );
  }

  const getShapeClass = () => {
    switch (iconShape) {
      case 'square':
        return 'rounded-none';
      case 'rounded':
        return 'rounded-2xl';
      case 'circle':
      default:
        return 'rounded-full';
    }
  };

  const getSizeClass = () => {
    switch (iconSize) {
      case 'small':
        return 'w-9 h-9 text-xs';
      case 'large':
        return 'w-14 h-14 text-base';
      case 'medium':
      default:
        return 'w-12 h-12 text-sm';
    }
  };

  const getCardStyle = (item) => {
    const brandColor = item.color || '#4648d4';
    let baseColor = brandColor;
    if (colorMode === 'black') baseColor = '#0f172a';
    if (colorMode === 'white') baseColor = '#ffffff';

    if (iconStyle === 'filled') {
      return {
        backgroundColor: baseColor,
        color: colorMode === 'white' ? '#0f172a' : '#ffffff',
        borderColor: 'transparent'
      };
    }

    if (iconStyle === 'unfilled') {
      return {
        backgroundColor: 'transparent',
        color: baseColor,
        borderColor: baseColor,
        borderWidth: '2px'
      };
    }

    // minimal
    return {
      backgroundColor: 'transparent',
      color: baseColor,
      borderColor: 'transparent',
      filter: 'drop-shadow(0 4px 8px rgba(0, 0, 0, 0.25))'
    };
  };

  return (
    <div className="w-full border-t border-slate-200 pt-3 mt-3">
      <div className="flex flex-wrap justify-center items-center gap-3.5 sm:gap-4">
        {activeLinks.map((item) => (
          <a
            key={item.platform}
            href={isPreview ? normalizeUrl(item.url) : 'javascript:void(0)'}
            target={isPreview ? '_blank' : '_self'}
            rel={isPreview ? 'noopener noreferrer' : undefined}
            onClick={(e) => {
              if (!isPreview) {
                e.preventDefault();
              }
            }}
            title={`${item.name}${!isPreview ? ' (Links active on Preview page)' : ''}`}
            style={getCardStyle(item)}
            className={`flex items-center justify-center border shadow-xs hover:scale-110 transition-all duration-200 cursor-pointer ${getShapeClass()} ${getSizeClass()}`}
          >
            <div className={`flex items-center justify-center transition-transform duration-200 ${iconStyle === 'minimal' ? 'scale-[1.35]' : ''}`}>
              {SOCIAL_ICONS[item.platform] || <span className="material-symbols-outlined text-[20px]">link</span>}
            </div>
          </a>
        ))}
      </div>
    </div>
  );
}
